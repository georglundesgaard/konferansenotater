// Henter hele transkripsjonen til en Vimeo-video fra sidens React-tilstand og gjør den klar for kopiering.
// Kjøres i brukerens Chrome (claude-in-chrome javascript_tool) på videosiden. Idempotent: kjør på nytt til «klar».
//
//   1. kjør → «venter …»  (klikker Transcript-knappen, poller etter cue-arrayet i React-treet)
//   2. kjør igjen etter noen sekunder → «klar: N cues …»  (teksten ligger i et skjult textarea, ett-gangs
//      klikk-handler på document er armert)
//   3. aktiver fanen (scripts/chrome-activate-tab.sh <url-del>), gjør ETT ekte CDP-klikk hvor som helst på siden
//   4. scripts/save-transcript.sh <fil> <tittel> <url> [språk]   (pbpaste + header + verifikasjon)
//
// Hvorfor så omstendelig: navigator.clipboard henger, execCommand('copy') virker bare i en trusted klikk-handler,
// og fetch/WebSocket mot localhost blokkeres av Private Network Access. Ikke skrap det virtualiserte panelet.
// Cue-arrayet ligger dypt i en hook-kjede (memoizedState.next.next…), så søket er et budsjettert dybdesøk fra
// React-rotene uten dybdegrense, med vern mot kastende gettere (spilleren har slike). Verifisert sept. 2026.
(() => {
  const S = (window.__vt = window.__vt || { status: 'start', tries: 0 });
  const hms = ms => { const s = Math.floor(ms / 1000); return [s / 3600, s % 3600 / 60, s % 60].map(v => String(Math.floor(v)).padStart(2, '0')).join(':'); };

  const findCues = () => {
    const isCue = a => Array.isArray(a) && a.length > 20 && a[0] && typeof a[0] === 'object' && 'cueStart' in a[0] && 'lines' in a[0];
    const roots = new Set();
    for (const el of document.querySelectorAll('*')) for (const k of Object.keys(el)) {
      if (k.startsWith('__reactFiber$')) { let f = el[k]; while (f.return) f = f.return; roots.add(f); }
      if (k.startsWith('__reactContainer$')) roots.add(el[k]);
    }
    const seen = new Set(); const stack = [...roots]; let budget = 3000000;
    while (stack.length && budget-- > 0) {
      const v = stack.pop();
      if (!v || typeof v !== 'object' || seen.has(v)) continue;
      seen.add(v);
      if (isCue(v)) return v;
      if (v instanceof Node || v instanceof Window) continue;
      let keys; try { keys = Object.keys(v); } catch (e) { continue; }
      for (const k of keys) {
        if (k === '_owner' || k === '_debugOwner' || k === 'alternate' || k === 'return' || k === '_reactInternals') continue;
        let c; try { c = v[k]; } catch (e) { continue; }
        if (c && typeof c === 'object') stack.push(c);
      }
    }
    return null;
  };

  const arm = () => {
    let ta = document.getElementById('__vt_ta');
    if (!ta) {
      ta = document.createElement('textarea'); ta.id = '__vt_ta';
      ta.style.cssText = 'position:fixed;left:0;top:0;width:2px;height:2px;opacity:0.01;z-index:2147483647';
      document.body.appendChild(ta);
    }
    ta.value = S.text;
    if (S.handler) document.removeEventListener('click', S.handler, true);
    S.handler = () => { ta.focus(); ta.select(); S.copied = document.execCommand('copy'); document.removeEventListener('click', S.handler, true); };
    document.addEventListener('click', S.handler, true);
  };

  if (S.status === 'klar') { arm(); return `klar: ${S.count} cues, språk ${S.language}, ${S.text.length} tegn. Armert for kopiering: aktiver fanen og gjør ett ekte klikk. Kopiert sist: ${S.copied ?? 'nei'}`; }

  const ready = cues => {
    S.count = cues.length; S.language = (cues[0].language || 'ukjent') + (cues[0].autogenerated ? ' (autogenerert)' : '');
    S.text = cues.map(c => `${hms(c.cueStart)} ${(c.lines || []).map(l => (l.text || '').trim()).join(' ')}`).join('\n');
    S.status = 'klar'; arm();
  };

  if (S.status === 'start') {
    const now = findCues();  // panelet kan alt være åpent: da må knappen IKKE klikkes (den lukker det)
    if (now) { ready(now); return `klar: ${S.count} cues, språk ${S.language}, ${S.text.length} tegn. Armert for kopiering: aktiver fanen og gjør ett ekte klikk.`; }
    // Siden har to Transcript-knapper: én i spillerens kontrollinje og én på selve siden. Foretrekk sidens.
    const btns = [...document.querySelectorAll('button')].filter(b => /transcript/i.test((b.textContent || '') + ' ' + (b.getAttribute('aria-label') || '')));
    const btn = btns.find(b => !b.closest('[id^="player"]')) || btns[0];
    if (btn) btn.click();
    S.status = 'venter';
    S.timer = setInterval(() => {
      S.tries++;
      const cues = findCues();
      if (cues) { clearInterval(S.timer); ready(cues); }
      else if (S.tries > 60) { clearInterval(S.timer); S.status = 'feil'; }
    }, 700);
    return btn ? 'venter: Transcript-knapp klikket, poller etter cues (kjør igjen om noen sekunder)' : 'venter: fant ingen Transcript-knapp, poller likevel';
  }
  if (S.status === 'feil') { S.status = 'start'; return 'feil: fant ingen cues på 40 s. Har videoen transkripsjon? Kjør igjen for nytt forsøk.'; }
  return `venter (${S.tries} forsøk) …`;
})();
